-- SGIC-Terneros: baseline relacional para un proyecto Supabase NUEVO.
-- Modelos de origen: backend/apps/*/models.py (Django).
-- No importa datos, no habilita operaciones cliente ni sustituye los servicios Django.
begin;

create table public.perfil (
  id uuid primary key references auth.users(id) on delete cascade,
  nombre text, rol text not null default 'OPERADOR' check (rol in ('ADMIN','OPERADOR')),
  activo boolean not null default true, creado_el timestamptz not null default now()
);
create table public.raza (
  id bigint generated by default as identity primary key,
  nombre varchar(80) not null unique
);
create table public.lote (
  id bigint generated by default as identity primary key,
  codigo varchar(30) not null unique,
  lote_origen_id bigint references public.lote(id) on delete restrict,
  fecha_ingreso date not null, cantidad_original integer not null default 0 check(cantidad_original>=0),
  cantidad_actual integer not null default 0 check(cantidad_actual>=0),
  estado varchar(20) not null default 'ACTIVO' check(estado in ('ACTIVO','CERRADO')),
  observaciones text, creado_el timestamptz not null default now(),
  check(lote_origen_id is distinct from id)
);
create table public.animal (
  id bigint generated by default as identity primary key,
  diio varchar(30) not null unique, lote_id bigint not null references public.lote(id) on delete restrict,
  raza_id bigint not null references public.raza(id) on delete restrict, sexo varchar(10) not null,
  fecha_nacimiento date, edad_aproximada_dias integer not null default 0 check(edad_aproximada_dias>=0),
  fecha_adquisicion date not null, precio_adquisicion numeric(12,2) not null check(precio_adquisicion>=0),
  peso_ingreso_kg numeric(8,2) check(peso_ingreso_kg>0),
  estado varchar(20) not null default 'ACTIVO' check(estado in ('ACTIVO','VENDIDO','FALLECIDO')),
  observaciones text
);
create index animal_lote_estado_idx on public.animal(lote_id,estado);
create table public.peso_animal (
  id bigint generated by default as identity primary key,
  animal_id bigint not null references public.animal(id) on delete restrict,
  fecha date not null, peso_kg numeric(8,2) not null check(peso_kg>0), observaciones text
);
create table public.proveedor (
  id bigint generated by default as identity primary key, nombre varchar(150) not null,
  rut varchar(20), telefono varchar(30), email varchar(120), direccion varchar(200), activo boolean not null default true
);
create table public.compra_animal (
  id bigint generated by default as identity primary key,
  fecha date not null, proveedor_id bigint references public.proveedor(id) on delete restrict,
  total numeric(12,2) not null check(total>=0), observaciones text
);
create table public.detalle_compra_animal (
  id bigint generated by default as identity primary key,
  compra_id bigint not null references public.compra_animal(id) on delete restrict,
  animal_id bigint not null unique references public.animal(id) on delete restrict,
  precio_adquisicion numeric(12,2) not null check(precio_adquisicion>=0),
  peso_compra numeric(8,2) check(peso_compra>0)
);
create table public.categoria_producto (
  id bigint generated by default as identity primary key, nombre varchar(80) not null unique,
  descripcion text, activo boolean not null default true
);
create table public.unidad_medida (
  id bigint generated by default as identity primary key, codigo varchar(20) not null unique,
  nombre varchar(50) not null, tipo varchar(30) not null, decimales integer not null default 2 check(decimales between 0 and 6)
);
create table public.producto (
  id bigint generated by default as identity primary key, nombre varchar(120) not null,
  categoria_id bigint not null references public.categoria_producto(id) on delete restrict,
  unidad_base_id bigint not null references public.unidad_medida(id) on delete restrict,
  stock_actual numeric(12,3) not null default 0 check(stock_actual>=0),
  stock_minimo numeric(12,3) not null default 0 check(stock_minimo>=0),
  costo_promedio numeric(12,2) not null default 0 check(costo_promedio>=0),
  activo boolean not null default true, observaciones text
);
create table public.presentacion_producto (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.producto(id) on delete restrict,
  nombre varchar(80) not null, cantidad_base numeric(12,3) not null check(cantidad_base>0),
  unidad_base_id bigint not null references public.unidad_medida(id) on delete restrict,
  activa boolean not null default true
);
create table public.conversion_producto (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.producto(id) on delete restrict,
  cantidad_origen numeric(12,4) not null check(cantidad_origen>0),
  unidad_origen_id bigint not null references public.unidad_medida(id) on delete restrict,
  cantidad_destino numeric(12,4) not null check(cantidad_destino>0),
  unidad_destino_id bigint not null references public.unidad_medida(id) on delete restrict,
  activa boolean not null default true
);
create table public.movimiento_inventario (
  id bigint generated by default as identity primary key,
  producto_id bigint not null references public.producto(id) on delete restrict,
  tipo varchar(30) not null check(tipo in ('ENTRADA','SALIDA','AJUSTE')),
  cantidad numeric(12,3) not null check(cantidad<>0),
  costo_unitario numeric(12,2) not null check(costo_unitario>=0),
  costo_total numeric(12,2) not null,
  fecha_hora timestamptz not null default now(),
  usuario_id uuid not null references auth.users(id) on delete restrict,
  referencia_tipo varchar(50) not null, referencia_id bigint, observaciones text
);
create index mov_inv_producto_fecha_idx on public.movimiento_inventario(producto_id,fecha_hora desc);
create table public.compra_insumo (
  id bigint generated by default as identity primary key,
  proveedor_id bigint not null references public.proveedor(id) on delete restrict,
  fecha date not null, numero_documento varchar(50),
  estado varchar(20) not null default 'BORRADOR' check(estado in ('BORRADOR','CONFIRMADA','ANULADA')),
  total numeric(12,2) not null check(total>=0), observaciones text
);
create table public.detalle_compra_insumo (
  id bigint generated by default as identity primary key,
  compra_id bigint not null references public.compra_insumo(id) on delete restrict,
  producto_id bigint not null references public.producto(id) on delete restrict,
  presentacion_id bigint references public.presentacion_producto(id) on delete restrict,
  cantidad numeric(12,3) not null check(cantidad>0),
  cantidad_base numeric(12,3) not null check(cantidad_base>0),
  precio_unitario numeric(12,2) not null check(precio_unitario>=0),
  subtotal numeric(12,2) not null check(subtotal>=0)
);
create table public.plan_consumo (
  id bigint generated by default as identity primary key,
  nombre varchar(100) not null, descripcion text, activo boolean not null default true, observaciones text
);
create table public.detalle_plan_consumo (
  id bigint generated by default as identity primary key,
  plan_id bigint not null references public.plan_consumo(id) on delete restrict,
  producto_id bigint not null references public.producto(id) on delete restrict,
  cantidad_diaria numeric(12,3) not null check(cantidad_diaria>0),
  unidad_id bigint not null references public.unidad_medida(id) on delete restrict, observaciones text
);
create table public.asignacion_plan_lote (
  id bigint generated by default as identity primary key,
  lote_id bigint not null references public.lote(id) on delete restrict,
  plan_id bigint not null references public.plan_consumo(id) on delete restrict,
  fecha_inicio date not null, fecha_fin date, activo boolean not null default true, observaciones text,
  check(fecha_fin is null or fecha_fin>=fecha_inicio)
);
create table public.consumo (
  id bigint generated by default as identity primary key,
  lote_id bigint references public.lote(id) on delete restrict,
  fecha date not null, origen varchar(20) not null check(origen in ('PLAN','REAL','AJUSTE')),
  usuario_id uuid not null references auth.users(id) on delete restrict, observaciones text
);
create table public.detalle_consumo (
  id bigint generated by default as identity primary key,
  consumo_id bigint not null references public.consumo(id) on delete restrict,
  producto_id bigint not null references public.producto(id) on delete restrict,
  cantidad numeric(12,3) not null check(cantidad>0),
  unidad_id bigint not null references public.unidad_medida(id) on delete restrict,
  costo_unitario numeric(12,2) not null check(costo_unitario>=0),
  costo_total numeric(12,2) not null check(costo_total>=0)
);
create table public.tratamiento (
  id bigint generated by default as identity primary key,
  animal_id bigint not null references public.animal(id) on delete restrict,
  producto_id bigint not null references public.producto(id) on delete restrict,
  fecha date not null, cantidad numeric(12,3) check(cantidad>0),
  costo_total numeric(12,2) check(costo_total>=0),
  motivo varchar(200) not null, observaciones text
);
create table public.categoria_gasto (
  id bigint generated by default as identity primary key, nombre varchar(80) not null unique, descripcion text
);
create table public.gasto (
  id bigint generated by default as identity primary key,
  categoria_id bigint not null references public.categoria_gasto(id) on delete restrict,
  lote_id bigint references public.lote(id) on delete restrict,
  fecha date not null, nombre varchar(120) not null, detalle text,
  monto numeric(12,2) not null check(monto>=0), observaciones text
);
create table public.venta (
  id bigint generated by default as identity primary key,
  fecha date not null, comprador varchar(150),
  peso_total_kg numeric(12,2) check(peso_total_kg>0),
  precio_kg numeric(12,2) check(precio_kg>=0),
  total_venta numeric(12,2) not null check(total_venta>=0),
  estado varchar(20) not null default 'BORRADOR' check(estado in ('BORRADOR','CONFIRMADA','ANULADA')),
  observaciones text
);
create table public.detalle_venta (
  id bigint generated by default as identity primary key,
  venta_id bigint not null references public.venta(id) on delete restrict,
  lote_id bigint not null references public.lote(id) on delete restrict,
  cantidad_animales integer not null check(cantidad_animales>0),
  ingreso numeric(12,2) not null default 0 check(ingreso>=0),
  costo_reconocido numeric(12,2) not null default 0 check(costo_reconocido>=0),
  utilidad numeric(12,2) not null default 0
);
-- Trazabilidad DIIO de ventas parciales, no implícita por orden de ID.
create table public.animal_venta (
  animal_id bigint primary key references public.animal(id) on delete restrict,
  detalle_venta_id bigint not null references public.detalle_venta(id) on delete restrict
);
create table public.registro_auditoria (
  id bigint generated by default as identity primary key,
  usuario_id uuid references auth.users(id) on delete restrict,
  fecha_hora timestamptz not null default now(),
  accion varchar(30) not null, modelo varchar(80) not null,
  objeto_id bigint, request_id uuid, motivo text,
  datos_anteriores jsonb, datos_nuevos jsonb
);
create index registro_auditoria_entidad_idx on public.registro_auditoria(modelo,objeto_id,fecha_hora desc);
create index registro_auditoria_usuario_idx on public.registro_auditoria(usuario_id,fecha_hora desc);

commit;
