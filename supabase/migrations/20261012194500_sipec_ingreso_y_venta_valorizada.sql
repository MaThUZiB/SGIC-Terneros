-- Importación supervisada de SIPECweb y venta con precios individuales.
-- No incluye datos de ganado, movimientos, semillas ni usuarios.
begin;

create table public.ingreso_sipec (
  id bigint generated by default as identity primary key,
  tipo text not null check(tipo in ('COMPRA','INICIAL','TRASLADO','NACIMIENTO')),
  fecha date not null,
  lote_id bigint not null references public.lote(id) on delete restrict,
  proveedor_id bigint references public.proveedor(id) on delete restrict,
  documento text,
  cantidad integer not null check(cantidad between 1 and 200),
  valor_total numeric(12,2) not null check(valor_total>0),
  creado_por uuid not null references auth.users(id) on delete restrict,
  creado_el timestamptz not null default now(),
  check(tipo='COMPRA' or proveedor_id is null)
);
create table public.ingreso_sipec_animal (
  ingreso_id bigint not null references public.ingreso_sipec(id) on delete restrict,
  animal_id bigint primary key references public.animal(id) on delete restrict,
  valor_base numeric(12,2) not null check(valor_base>0),
  raza_sipec text not null,
  categoria_sipec text,
  establecimiento_sipec text
);
create index ingreso_sipec_fecha_idx on public.ingreso_sipec(fecha desc);
create index ingreso_sipec_animal_ingreso_idx on public.ingreso_sipec_animal(ingreso_id);

create table public.venta_precio_animal (
  animal_id bigint primary key references public.animal(id) on delete restrict,
  venta_id bigint not null references public.venta(id) on delete restrict,
  precio_venta numeric(12,2) not null check(precio_venta>=0)
);
create index venta_precio_animal_venta_idx on public.venta_precio_animal(venta_id);

alter table public.ingreso_sipec enable row level security;
alter table public.ingreso_sipec_animal enable row level security;
alter table public.venta_precio_animal enable row level security;
revoke all on public.ingreso_sipec,public.ingreso_sipec_animal,public.venta_precio_animal from public,anon,authenticated;
grant select on public.ingreso_sipec,public.ingreso_sipec_animal,public.venta_precio_animal to authenticated;

create policy lectura_ingreso_sipec_admin on public.ingreso_sipec
  for select to authenticated using (
    exists(select 1 from public.perfil p where p.id=auth.uid() and p.activo and p.rol='ADMIN')
  );
create policy lectura_ingreso_sipec_animal_admin on public.ingreso_sipec_animal
  for select to authenticated using (
    exists(select 1 from public.perfil p where p.id=auth.uid() and p.activo and p.rol='ADMIN')
  );
create policy lectura_precio_venta_admin on public.venta_precio_animal
  for select to authenticated using (
    exists(select 1 from public.perfil p where p.id=auth.uid() and p.activo and p.rol='ADMIN')
  );

create or replace function public.sgic_incorporar_desde_sipec(
  p_tipo text, p_fecha date, p_lote_id bigint, p_lote_codigo text,
  p_proveedor_id bigint, p_documento text, p_animales jsonb
) returns bigint language plpgsql security definer set search_path=''
as $fn$
declare
  v_actor uuid;
  v_tipo text;
  v_lote bigint;
  v_ingreso bigint;
  v_compra bigint;
  v_animal bigint;
  v_raza bigint;
  v_nombre text;
  v_diio text;
  v_sexo text;
  v_nacimiento date;
  v_valor numeric(12,2);
  v_total numeric(12,2):=0;
  v_cantidad int;
  v_item jsonb;
begin
  v_actor:=sgic_private.actor(true);
  v_tipo:=upper(trim(coalesce(p_tipo,'')));
  if v_tipo not in ('COMPRA','INICIAL','TRASLADO','NACIMIENTO') then
    raise exception 'Tipo de ingreso SIPECweb no admitido';
  end if;
  if p_fecha is null then raise exception 'Indique fecha de incorporación'; end if;
  if jsonb_typeof(p_animales) is distinct from 'array' then
    raise exception 'Detalle de animales inválido';
  end if;
  v_cantidad:=jsonb_array_length(p_animales);
  if v_cantidad<1 or v_cantidad>200 then
    raise exception 'Seleccione entre 1 y 200 animales por ingreso';
  end if;
  if v_tipo<>'COMPRA' and p_proveedor_id is not null then
    raise exception 'Proveedor solo corresponde a una compra';
  end if;
  if p_proveedor_id is not null and not exists (
    select 1 from public.proveedor where id=p_proveedor_id and activo
  ) then raise exception 'Proveedor no disponible'; end if;

  -- Bloqueo de lote para operaciones concurrentes; la unicidad de animal.diio
  -- garantiza rechazo atómico ante el mismo animal importado simultáneamente.
  if p_lote_id is not null then
    if nullif(trim(coalesce(p_lote_codigo,'')),'') is not null then
      raise exception 'Seleccione lote existente o cree uno nuevo, no ambos';
    end if;
    select id into v_lote from public.lote
      where id=p_lote_id and estado='ACTIVO' for update;
    if v_lote is null then raise exception 'Lote no disponible'; end if;
  else
    if nullif(trim(coalesce(p_lote_codigo,'')),'') is null
       or length(trim(p_lote_codigo))>30 then
      raise exception 'Indique código de lote nuevo (máximo 30 caracteres)';
    end if;
    insert into public.lote(codigo,fecha_ingreso,cantidad_original,cantidad_actual)
      values(trim(p_lote_codigo),p_fecha,0,0) returning id into v_lote;
  end if;

  insert into public.ingreso_sipec(tipo,fecha,lote_id,proveedor_id,documento,cantidad,valor_total,creado_por)
    values(v_tipo,p_fecha,v_lote,p_proveedor_id,nullif(trim(coalesce(p_documento,'')),''),v_cantidad,1,v_actor)
    returning id into v_ingreso;

  if v_tipo='COMPRA' then
    insert into public.compra_animal(fecha,proveedor_id,total,observaciones)
      values(p_fecha,p_proveedor_id,0,'Ingreso SIPECweb #'||v_ingreso) returning id into v_compra;
  end if;

  for v_item in select value from jsonb_array_elements(p_animales) loop
    if jsonb_typeof(v_item) <> 'object' then
      raise exception 'El detalle debe contener animales individuales';
    end if;
    v_diio:=trim(coalesce(v_item->>'diio',''));
    v_sexo:=upper(trim(coalesce(v_item->>'sexo','')));
    v_nombre:=upper(trim(coalesce(v_item->>'raza_nombre','')));
    if v_diio !~ '^[0-9]{7,15}$' then raise exception 'DIIO inválido: %',v_diio; end if;
    if v_sexo not in ('MACHO','HEMBRA') then raise exception 'Sexo inválido para DIIO %',v_diio; end if;
    if nullif(v_item->>'valor_base','') is null then
      raise exception 'Complete valor económico para DIIO %',v_diio;
    end if;
    v_valor:=(v_item->>'valor_base')::numeric(12,2);
    if v_valor<=0 then raise exception 'El valor del DIIO % debe ser mayor que cero',v_diio; end if;
    v_nacimiento:=nullif(v_item->>'fecha_nacimiento','')::date;
    if v_nacimiento is not null and v_nacimiento>p_fecha then
      raise exception 'Nacimiento posterior al ingreso para DIIO %',v_diio;
    end if;

    if nullif(v_item->>'raza_id','') is not null then
      v_raza:=(v_item->>'raza_id')::bigint;
      if not exists(select 1 from public.raza where id=v_raza) then
        raise exception 'Raza seleccionada no disponible para DIIO %',v_diio;
      end if;
    else
      if v_nombre='' or length(v_nombre)>80 then
        raise exception 'Indique raza válida para DIIO %',v_diio;
      end if;
      insert into public.raza(nombre) values(v_nombre) on conflict(nombre) do nothing;
      select id into v_raza from public.raza where nombre=v_nombre;
      if v_raza is null then raise exception 'No se pudo resolver la raza'; end if;
    end if;

    insert into public.animal(
      diio,lote_id,raza_id,sexo,fecha_nacimiento,edad_aproximada_dias,
      fecha_adquisicion,precio_adquisicion,estado
    ) values(
      v_diio,v_lote,v_raza,v_sexo,v_nacimiento,
      coalesce(p_fecha-v_nacimiento,0),p_fecha,v_valor,'ACTIVO'
    ) returning id into v_animal;

    insert into public.ingreso_sipec_animal(
      ingreso_id,animal_id,valor_base,raza_sipec,categoria_sipec,establecimiento_sipec
    ) values(
      v_ingreso,v_animal,v_valor,trim(coalesce(v_item->>'raza_sipec','')),
      nullif(trim(coalesce(v_item->>'categoria_sipec','')),''),
      nullif(trim(coalesce(v_item->>'establecimiento_sipec','')),'')
    );

    if v_tipo='COMPRA' then
      insert into public.detalle_compra_animal(compra_id,animal_id,precio_adquisicion)
        values(v_compra,v_animal,v_valor);
    end if;
    v_total:=v_total+v_valor;
  end loop;

  update public.ingreso_sipec set valor_total=v_total where id=v_ingreso;
  if v_compra is not null then
    update public.compra_animal set total=v_total where id=v_compra;
  end if;
  update public.lote
    set cantidad_original=cantidad_original+v_cantidad,cantidad_actual=cantidad_actual+v_cantidad
    where id=v_lote;
  perform sgic_private.audit(v_actor,'CREAR','ingreso_sipec',v_ingreso,
    jsonb_build_object('tipo',v_tipo,'cantidad',v_cantidad,'valor_total',v_total,
      'lote_id',v_lote,'compra_id',v_compra));
  return v_ingreso;
end;
$fn$;
revoke all on function public.sgic_incorporar_desde_sipec(text,date,bigint,text,bigint,text,jsonb) from public,anon;
grant execute on function public.sgic_incorporar_desde_sipec(text,date,bigint,text,bigint,text,jsonb) to authenticated;

-- Una venta con detalle económico individual utiliza la liquidación existente
-- de costos por lote; luego distribuye ingresos según precios efectivos por DIIO.
create or replace function public.sgic_venta_precios_individuales(
  p_animales jsonb,p_comprador text,p_fecha date
) returns bigint language plpgsql security definer set search_path=''
as $fn$
declare
  v_actor uuid;
  v_venta bigint;
  v_ids bigint[]:=array[]::bigint[];
  v_total numeric(12,2):=0;
  v_animal_id bigint;
  v_precio numeric(12,2);
  v_item jsonb;
  v_count integer;
begin
  v_actor:=sgic_private.actor(true);
  if p_fecha is null or jsonb_typeof(p_animales) is distinct from 'array' then
    raise exception 'Datos de venta inválidos';
  end if;
  v_count:=jsonb_array_length(p_animales);
  if v_count<1 or v_count>200 then
    raise exception 'Seleccione entre 1 y 200 animales';
  end if;
  for v_item in select value from jsonb_array_elements(p_animales) loop
    if jsonb_typeof(v_item)<>'object' or
       nullif(v_item->>'animal_id','') is null or
       nullif(v_item->>'precio_venta','') is null then
      raise exception 'Complete DIIO y precio de venta';
    end if;
    v_animal_id:=(v_item->>'animal_id')::bigint;
    v_precio:=(v_item->>'precio_venta')::numeric(12,2);
    if v_precio<0 then raise exception 'Precio de venta negativo no permitido'; end if;
    if v_animal_id=any(v_ids) then raise exception 'DIIO duplicado en la venta'; end if;
    v_ids:=array_append(v_ids,v_animal_id);
    v_total:=v_total+v_precio;
  end loop;
  if v_total<=0 then raise exception 'La venta debe tener un importe mayor que cero'; end if;

  v_venta:=sgic_private.finalizar_venta(v_ids,v_total,coalesce(p_comprador,''),p_fecha,null);

  insert into public.venta_precio_animal(venta_id,animal_id,precio_venta)
    select v_venta,(value->>'animal_id')::bigint,(value->>'precio_venta')::numeric(12,2)
    from jsonb_array_elements(p_animales);

  with importes as (
    select dv.id as detalle_id,sum(vpa.precio_venta)::numeric(12,2) as ingreso_individual
    from public.detalle_venta dv
    join public.animal_venta av on av.detalle_venta_id=dv.id
    join public.venta_precio_animal vpa on vpa.animal_id=av.animal_id and vpa.venta_id=dv.venta_id
    where dv.venta_id=v_venta
    group by dv.id
  )
  update public.detalle_venta dv
  set ingreso=i.ingreso_individual, utilidad=i.ingreso_individual-dv.costo_reconocido
  from importes i where dv.id=i.detalle_id;

  perform sgic_private.audit(v_actor,'VALORIZAR','venta',v_venta,
    jsonb_build_object('precio_por_diio',true,'cantidad',v_count,'total',v_total));
  return v_venta;
end;
$fn$;
revoke all on function public.sgic_venta_precios_individuales(jsonb,text,date) from public,anon;
grant execute on function public.sgic_venta_precios_individuales(jsonb,text,date) to authenticated;

commit;
