create or replace function sgic_private.copiar_modo_plan()
returns trigger language plpgsql set search_path='' as $fn$
begin
  select p.modo_racion into new.modo_racion
  from public.plan_consumo p where p.id=new.plan_id;
  if new.modo_racion is null then raise exception 'Plan inexistente'; end if;
  return new;
end $fn$;
drop trigger if exists sgic_snapshot_modo_plan on public.asignacion_plan_lote;
create trigger sgic_snapshot_modo_plan before insert on public.asignacion_plan_lote
for each row execute function sgic_private.copiar_modo_plan();

create or replace function public.sgic_configurar_modo_plan(p_plan_id bigint,p_modo text)
returns text language plpgsql security definer set search_path='' as $fn$
declare v_actor uuid:=sgic_private.actor(true); v_nombre text;
begin
  if p_modo not in ('LOTE','ANIMAL') or p_modo is null then raise exception 'Modo inválido'; end if;
  select nombre into v_nombre from public.plan_consumo where id=p_plan_id for update;
  if not found then raise exception 'Plan inexistente'; end if;
  if exists(select 1 from public.asignacion_plan_lote where plan_id=p_plan_id) then
    raise exception 'El modo de un plan con asignaciones históricas no puede modificarse; crea otro plan.';
  end if;
  update public.plan_consumo set modo_racion=p_modo where id=p_plan_id;
  perform sgic_private.audit(v_actor,'CONFIGURAR','plan_consumo',p_plan_id,
    jsonb_build_object('modo_racion',p_modo,'nombre',v_nombre));
  return p_modo;
end $fn$;
revoke all on function public.sgic_configurar_modo_plan(bigint,text) from public,anon;
grant execute on function public.sgic_configurar_modo_plan(bigint,text) to authenticated;

