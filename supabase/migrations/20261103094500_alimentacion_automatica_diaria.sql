-- Ejecuta el cargo de una fecha dada, solo desde la base de datos (sin Data API).
create or replace function sgic_private.aplicar_alimentacion_automatica(p_fecha date)
returns jsonb language plpgsql set search_path='' as $fn$
declare
  a record; d record; p record;
  v_cantidad numeric; v_costo numeric; v_consumo bigint;
  v_animales integer; v_lineas integer; v_aplicados integer:=0; v_errores integer:=0;
  v_omitidos integer:=0; v_error text; v_modo text;
  v_hoy date:=(now() at time zone 'America/Santiago')::date;
begin
  if p_fecha is null or p_fecha > v_hoy or p_fecha < date '2026-11-03'
     or p_fecha < v_hoy-7 then
    raise exception 'Fecha fuera de la ventana de ejecución automática';
  end if;
  -- La hora de ejecución es controlada por cron; no procesa una jornada futura.
  if not pg_catalog.pg_try_advisory_xact_lock(pg_catalog.hashtextextended(
      'sgic_alimentacion_automatica:'||p_fecha::text,0)) then
    return jsonb_build_object('fecha',p_fecha,'estado','OCUPADO');
  end if;
  for a in
    select a.id,a.lote_id,a.componentes,a.modo_racion,l.cantidad_actual
    from public.asignacion_plan_lote a
    join public.lote l on l.id=a.lote_id
    where l.estado='ACTIVO'
      and a.fecha_inicio<=p_fecha and (a.fecha_fin is null or a.fecha_fin>=p_fecha)
      and not (a.fecha_inicio=a.fecha_fin and a.observaciones like '%SGIC_SIN_EJECUCION%')
    order by a.lote_id,a.id
  loop
    v_animales:=greatest(a.cantidad_actual,0);
    if exists(select 1 from public.consumo where lote_id=a.lote_id and fecha=p_fecha and origen='PLAN') then
      -- También protege contra confirmaciones realizadas en clientes antiguos.
      continue;
    end if;
    if exists(select 1 from public.consumo where lote_id=a.lote_id and fecha=p_fecha and origen='REAL') then
      insert into public.sgic_alimentacion_auto_evento(lote_id,asignacion_id,fecha,estado,animales,detalle)
      values(a.lote_id,a.id,p_fecha,'OMITIDO_MANUAL',v_animales,'Hay alimentación manual en esta jornada; se evitó la duplicación.')
      on conflict(lote_id,fecha) do update set estado=excluded.estado,asignacion_id=excluded.asignacion_id,
        detalle=excluded.detalle,animales=excluded.animales,actualizado_en=now();
      v_omitidos:=v_omitidos+1;
      continue;
    end if;
    begin
      if v_animales<=0 then raise exception 'Lote sin animales activos'; end if;
      if jsonb_typeof(a.componentes) is distinct from 'array'
          or jsonb_array_length(a.componentes)=0 then raise exception 'Plan sin alimentos'; end if;
      v_modo:=a.modo_racion;
      -- Bloqueo de productos ordenado y validación previa (sin descontar parcialmente).
      for p in
        select (e.value->>'producto_id')::bigint id,
          sum(case when v_modo='ANIMAL'
            then round((e.value->>'cantidad_diaria')::numeric*v_animales,3)
            else (e.value->>'cantidad_diaria')::numeric end) cantidad
        from jsonb_array_elements(a.componentes) e
        group by (e.value->>'producto_id')::bigint order by 1
      loop
        select stock_actual,activo,apto_plan into d
        from public.producto where id=p.id for update;
        if not found or not coalesce(d.activo,false) or not coalesce(d.apto_plan,false) then
          raise exception 'Insumo % no disponible para alimentación',p.id;
        end if;
        if p.cantidad<=0 or p.cantidad<>round(p.cantidad,3) then
          raise exception 'Cantidad diaria inválida del insumo %',p.id;
        end if;
        if d.stock_actual<p.cantidad then
          raise exception 'Stock insuficiente del insumo %: requiere %, disponible %',
            p.id,p.cantidad,d.stock_actual;
        end if;
      end loop;
      insert into public.consumo(lote_id,fecha,origen,usuario_id,observaciones)
      values(a.lote_id,p_fecha,'PLAN',null,
        'AUTO_PLAN_ASIGNACION:'||a.id||'|ANIMALES:'||v_animales||'|MODO:'||v_modo)
      returning id into v_consumo;
      v_lineas:=0;
      for d in
        select (e.value->>'producto_id')::bigint producto_id,
          (e.value->>'unidad_id')::bigint unidad_id,
          case when v_modo='ANIMAL'
            then round((e.value->>'cantidad_diaria')::numeric*v_animales,3)
            else (e.value->>'cantidad_diaria')::numeric end as cantidad
        from jsonb_array_elements(a.componentes) e
        order by (e.value->>'producto_id')::bigint,(e.value->>'id')::bigint
      loop
        if d.cantidad<=0 or d.cantidad<>round(d.cantidad,3) then
          raise exception 'Cantidad de línea inválida';
        end if;
        v_costo:=sgic_private.stock_salida(d.producto_id,d.cantidad,null,'CONSUMO_PLAN',v_consumo);
        insert into public.detalle_consumo(consumo_id,producto_id,cantidad,unidad_id,costo_unitario,costo_total)
        select v_consumo,d.producto_id,d.cantidad,p.unidad_base_id,p.costo_promedio,v_costo
        from public.producto p where p.id=d.producto_id;
        v_lineas:=v_lineas+1;
      end loop;
      if v_lineas=0 then raise exception 'No hay consumos positivos en el plan'; end if;
      insert into public.sgic_alimentacion_auto_evento(lote_id,asignacion_id,fecha,estado,animales,consumo_id,detalle)
      values(a.lote_id,a.id,p_fecha,'APLICADO',v_animales,v_consumo,'Cargo automático basado en el plan.')
      on conflict(lote_id,fecha) do update set estado=excluded.estado,asignacion_id=excluded.asignacion_id,
        animales=excluded.animales,consumo_id=excluded.consumo_id,detalle=excluded.detalle,
        intentos=sgic_alimentacion_auto_evento.intentos+1,actualizado_en=now();
      v_aplicados:=v_aplicados+1;
    exception when others then
      -- EXCEPTION crea un subbloque transaccional: se revierte TODO el consumo fallido.
      get stacked diagnostics v_error=message_text;
      insert into public.sgic_alimentacion_auto_evento(lote_id,asignacion_id,fecha,estado,animales,detalle)
      values(a.lote_id,a.id,p_fecha,'ERROR',v_animales,left(v_error,500))
      on conflict(lote_id,fecha) do update set estado=excluded.estado,asignacion_id=excluded.asignacion_id,
        animales=excluded.animales,detalle=excluded.detalle,
        intentos=sgic_alimentacion_auto_evento.intentos+1,actualizado_en=now();
      v_errores:=v_errores+1;
    end;
  end loop;
  return jsonb_build_object('fecha',p_fecha,'aplicados',v_aplicados,
    'errores',v_errores,'omitidos_por_registro_manual',v_omitidos);
end $fn$;
revoke all on function sgic_private.aplicar_alimentacion_automatica(date) from public,anon,authenticated;

create or replace function sgic_private.ejecutar_alimentacion_programada()
returns jsonb language plpgsql set search_path='' as $fn$
declare d date; v_hoy date:=(now() at time zone 'America/Santiago')::date;
  v_hora integer:=extract(hour from now() at time zone 'America/Santiago');
  v_res jsonb:='[]'::jsonb;
begin
  -- Una jornada se carga después de las 23:00 de Chile; horas UTC y cambios DST no afectan.
  -- Reintento automático de los últimos siete días si faltó inventario o hubo caída del cron.
  for d in select generate_series(greatest(v_hoy-7,date '2026-11-03'),
     case when v_hora>=23 then v_hoy else v_hoy-1 end,'1 day'::interval)::date
  loop
    v_res:=v_res||jsonb_build_array(sgic_private.aplicar_alimentacion_automatica(d));
  end loop;
  return v_res;
end $fn$;
revoke all on function sgic_private.ejecutar_alimentacion_programada() from public,anon,authenticated;

