-- SGIC: alimentación por períodos declarados, sin raciones diarias automáticas.
-- El historial existente de consumos manuales se conserva.
begin;

-- Detener el proceso legado ANTES de retirar sus tablas.
do $$
begin
  if exists(select 1 from cron.job where jobname='sgic-alimentacion-automatica') then
    perform cron.unschedule('sgic-alimentacion-automatica');
  end if;
end $$;

-- No eliminar trazabilidad ni salidas de inventario originadas por planes.
do $$
begin
  if exists(select 1 from public.consumo where origen='PLAN')
    or exists(select 1 from public.movimiento_inventario where referencia_tipo='CONSUMO_PLAN') then
    raise exception 'Se detectaron consumos de planes antiguos. Revisar y migrar manualmente antes de retirar el esquema.';
  end if;
end $$;

create table public.periodo_alimentacion (
  id bigint generated by default as identity primary key,
  solicitud uuid not null unique,
  lote_id bigint not null references public.lote(id) on delete restrict,
  fecha_inicio date not null,
  fecha_fin date not null,
  estado text not null check (estado in ('ESTIMADO','DESCONTADO')),
  observaciones text,
  consumo_id bigint unique references public.consumo(id) on delete restrict,
  usuario_id uuid not null references auth.users(id) on delete restrict,
  creado_en timestamptz not null default now(),
  constraint periodo_alimentacion_fechas check(fecha_inicio <= fecha_fin),
  constraint periodo_alimentacion_estado_consumo check (
    (estado='ESTIMADO' and consumo_id is null) or
    (estado='DESCONTADO' and consumo_id is not null)
  )
);
create index periodo_alimentacion_lote_fecha on public.periodo_alimentacion(lote_id,fecha_fin desc);
create table public.detalle_periodo_alimentacion (
  id bigint generated by default as identity primary key,
  periodo_id bigint not null references public.periodo_alimentacion(id) on delete restrict,
  producto_id bigint not null references public.producto(id) on delete restrict,
  cantidad_total numeric(16,3) not null check (cantidad_total>0),
  unidad_id bigint not null references public.unidad_medida(id) on delete restrict,
  costo_referencia numeric(16,2) not null default 0 check (costo_referencia>=0),
  unique(periodo_id,producto_id)
);
create index detalle_periodo_alimentacion_producto on public.detalle_periodo_alimentacion(producto_id);
alter table public.periodo_alimentacion enable row level security;
alter table public.detalle_periodo_alimentacion enable row level security;
revoke all on public.periodo_alimentacion,public.detalle_periodo_alimentacion from public,anon;
grant select on public.periodo_alimentacion,public.detalle_periodo_alimentacion to authenticated;
create policy periodo_alimentacion_lectura on public.periodo_alimentacion for select to authenticated
 using (exists(select 1 from public.perfil where id=(select auth.uid()) and activo=true));
create policy detalle_periodo_alimentacion_lectura on public.detalle_periodo_alimentacion for select to authenticated
 using (exists(select 1 from public.perfil where id=(select auth.uid()) and activo=true));

create function public.sgic_registrar_periodo_alimentacion(p jsonb)
returns bigint language plpgsql security definer set search_path='' as $fn$
declare
  actor uuid:=sgic_private.actor();
  solicitud_id uuid;
  lote bigint;
  inicial date;
  final date;
  actual date:=(now() at time zone 'America/Santiago')::date;
  descontar boolean;
  nota text;
  r bigint;
  consumo_registro bigint;
  detalle record;
  producto record;
  costo numeric;
  total_items integer;
begin
  if p is null or jsonb_typeof(p) <> 'object' then raise exception 'Datos inválidos'; end if;
  solicitud_id:=(p->>'solicitud')::uuid;
  lote:=(p->>'lote_id')::bigint;
  inicial:=(p->>'fecha_inicio')::date;
  final:=(p->>'fecha_fin')::date;
  descontar:=coalesce((p->>'descontar_stock')::boolean,false);
  nota:=nullif(left(trim(coalesce(p->>'observaciones','')),500),'');
  if solicitud_id is null or lote is null or inicial is null or final is null then
    raise exception 'Lote, fechas e identificador son obligatorios';
  end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended(solicitud_id::text,0));
  select id into r from public.periodo_alimentacion where solicitud=solicitud_id;
  if found then return r; end if;
  if inicial>final or final>actual or final-inicial>365 then
    raise exception 'El período debe terminar a más tardar hoy y durar como máximo 366 días';
  end if;
  perform 1 from public.lote where id=lote for update;
  if not found then raise exception 'Lote inexistente'; end if;
  if exists (
    select 1 from public.periodo_alimentacion x
    where x.lote_id=lote and x.fecha_inicio<=final and x.fecha_fin>=inicial
  ) then raise exception 'El lote ya tiene un período que se superpone con estas fechas'; end if;
  -- No volver a cargar como período las jornadas que ya se descontaron manualmente.
  if exists (
    select 1 from public.consumo c
    where c.lote_id=lote and c.fecha between inicial and final and c.origen in ('REAL','PLAN')
  ) then raise exception 'Ya existen consumos diarios en estas fechas; revisa el historial antes de registrar un período'; end if;
  if jsonb_typeof(p->'detalles') is distinct from 'array' then
    raise exception 'Debes agregar insumos al período';
  end if;
  total_items:=jsonb_array_length(p->'detalles');
  if total_items<1 or total_items>20 then raise exception 'Agrega de 1 a 20 insumos'; end if;
  if (select count(distinct (value->>'producto_id')::bigint) from jsonb_array_elements(p->'detalles'))
    <> total_items then raise exception 'No repitas un insumo en el mismo período'; end if;
  -- Validar todos los renglones y bloquear existencias ANTES de registrar el período.
  for detalle in
    select (value->>'producto_id')::bigint as producto_id,
           (value->>'cantidad')::numeric as cantidad
    from jsonb_array_elements(p->'detalles')
    order by 1
  loop
    if detalle.producto_id is null or detalle.cantidad is null or
       detalle.cantidad<=0 or detalle.cantidad<>round(detalle.cantidad,3) then
      raise exception 'Cada insumo debe tener una cantidad positiva con hasta tres decimales';
    end if;
    select id,unidad_base_id,stock_actual,costo_promedio,activo,tipo_insumo,nombre
      into producto from public.producto where id=detalle.producto_id for update;
    if not found or not producto.activo or producto.tipo_insumo not in ('LECHE','CONCENTRADO') then
      raise exception 'Selecciona solo insumos activos de leche o concentrado';
    end if;
    if descontar and producto.stock_actual<detalle.cantidad then
      raise exception 'Stock insuficiente para %: disponible %, solicitado %',
        producto.nombre,producto.stock_actual,detalle.cantidad;
    end if;
  end loop;
  if descontar then
    insert into public.consumo(lote_id,fecha,origen,usuario_id,observaciones)
    values(lote,final,'REAL',actor,'Consumo aproximado consolidado por período')
    returning id into consumo_registro;
  end if;
  insert into public.periodo_alimentacion(solicitud,lote_id,fecha_inicio,fecha_fin,estado,observaciones,consumo_id,usuario_id)
  values(solicitud_id,lote,inicial,final,case when descontar then 'DESCONTADO' else 'ESTIMADO' end,
     nota,consumo_registro,actor) returning id into r;
  if consumo_registro is not null then
    update public.consumo set observaciones='PERIODO_ALIMENTACION:'||r||'|APROXIMADO' where id=consumo_registro;
  end if;
  for detalle in
    select (value->>'producto_id')::bigint as producto_id,
           (value->>'cantidad')::numeric as cantidad
    from jsonb_array_elements(p->'detalles')
    order by 1
  loop
    select unidad_base_id,costo_promedio into producto
      from public.producto where id=detalle.producto_id for update;
    costo:=round(detalle.cantidad*producto.costo_promedio,2);
    if descontar then
      costo:=sgic_private.stock_salida(detalle.producto_id,detalle.cantidad,actor,'CONSUMO_PERIODO',consumo_registro);
      insert into public.detalle_consumo(consumo_id,producto_id,cantidad,unidad_id,costo_unitario,costo_total)
      values(consumo_registro,detalle.producto_id,detalle.cantidad,producto.unidad_base_id,producto.costo_promedio,costo);
    end if;
    insert into public.detalle_periodo_alimentacion(periodo_id,producto_id,cantidad_total,unidad_id,costo_referencia)
    values(r,detalle.producto_id,detalle.cantidad,producto.unidad_base_id,costo);
  end loop;
  perform sgic_private.audit(actor,'CREAR','periodo_alimentacion',r,
    jsonb_build_object('lote_id',lote,'fecha_inicio',inicial,'fecha_fin',final,
       'descontado',descontar,'insumos',total_items,'consumo_id',consumo_registro));
  return r;
end $fn$;
revoke all on function public.sgic_registrar_periodo_alimentacion(jsonb) from public,anon;
grant execute on function public.sgic_registrar_periodo_alimentacion(jsonb) to authenticated;

